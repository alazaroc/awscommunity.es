import { chromium } from '@playwright/test';
const url = process.argv[2];
const out = process.argv[3];
const scrollY = Number(process.argv[4] || 0);
const reducedMotion = process.argv[5] === 'reduce' ? 'reduce' : 'no-preference';
const width = Number(process.argv[6] || 1440);
const height = Number(process.argv[7] || 900);
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width, height }, reducedMotion });
await page.goto(url, { waitUntil: 'networkidle' });
await page.waitForTimeout(800);
await page.evaluate((y) => window.scrollTo(0, y), scrollY);
await page.waitForTimeout(800);
await page.screenshot({ path: out });
await browser.close();
console.log('saved', out, 'scrollY', scrollY, 'motion', reducedMotion, width + 'x' + height);
