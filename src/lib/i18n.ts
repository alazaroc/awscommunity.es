export type TranslationKey = keyof typeof translations.es;

export function t(locale: Locale, key: TranslationKey, values: Record<string, string | number> = {}): string {
  let value: string = translations[locale][key] ?? translations.es[key];
  for (const [name, replacement] of Object.entries(values)) value = value.replaceAll(`{${name}}`, String(replacement));
  return value;
}

export function localeTag(locale: Locale): string {
  return LOCALE_TAG[locale];
}

export function localizedPath(locale: Locale, path: string): string {
  const clean = path.startsWith('/') ? path : `/${path}`;
  if (locale === 'es') return clean === '/' ? '/' : clean;
  return clean === '/' ? '/en/' : `/en${clean}`;
}

export function switchLocalePath(pathname: string, locale: Locale): string {
  const spanishPath = pathname.replace(/^\/en(?=\/|$)/, '') || '/';
  return localizedPath(locale, spanishPath);
}

export function localeFromPath(pathname: string): Locale {
  return pathname === '/en' || pathname.startsWith('/en/') ? 'en' : DEFAULT_LOCALE;
}

